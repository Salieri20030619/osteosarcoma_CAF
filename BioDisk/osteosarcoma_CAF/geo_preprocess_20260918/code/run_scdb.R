suppressPackageStartupMessages(library(scDblFinder))
suppressPackageStartupMessages(library(SingleCellExperiment))
suppressPackageStartupMessages(library(Matrix))
suppressPackageStartupMessages(library(BiocParallel))
root <- '/mnt/BioDisk/wangmingyuan/osteosarcoma_CAF/geo_preprocess_20260918/doublet_review'
samples <- read.delim(file.path(root,'manifest.tsv'),stringsAsFactors=FALSE)$sample
result <- list()
for (sm in samples) {
 cat('SCDB_START',sm,format(Sys.time()),'\n');flush.console()
 d <- file.path(root,sm)
 x <- as(readMM(gzfile(file.path(d,'counts.mtx.gz'))),'CsparseMatrix')
 rownames(x) <- readLines(file.path(d,'genes.tsv'))
 colnames(x) <- readLines(file.path(d,'cells.tsv'))
 stopifnot(all(Matrix::colSums(x)>0),!anyDuplicated(colnames(x)))
 set.seed(270231)
 a <- SingleCellExperiment(list(counts=x))
 a <- scDblFinder(a,clusters=NULL,dbr=0.06,dbr.sd=1,BPPARAM=SerialParam(RNGseed=270231,progressbar=FALSE))
 o <- data.frame(cell_id=colnames(a),scDblFinder_score=a$scDblFinder.score,scDblFinder_class=as.character(a$scDblFinder.class))
 stopifnot(nrow(o)==ncol(x),all(is.finite(o$scDblFinder_score)),all(o$scDblFinder_class %in% c('singlet','doublet')))
 write.table(o,file.path(d,'calls.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
 result[[sm]] <- data.frame(sample=sm,cells=nrow(o),doublets=sum(o$scDblFinder_class=='doublet'),fraction=mean(o$scDblFinder_class=='doublet'))
 write.table(do.call(rbind,result),file.path(root,'summary.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
 saveRDS(metadata(a),file.path(d,'model_metadata.rds'))
 writeLines('SCDB_SAMPLE_COMPLETE',file.path(d,'COMPLETE'))
 cat('SCDB_COMPLETE',sm,sum(o$scDblFinder_class=='doublet'),'\n');flush.console()
 rm(a,x,o);gc()
}
writeLines(capture.output(sessionInfo()),file.path(root,'R_sessionInfo.txt'))
writeLines('SCDB_REVIEW_COMPLETE',file.path(root,'COMPLETE'))
