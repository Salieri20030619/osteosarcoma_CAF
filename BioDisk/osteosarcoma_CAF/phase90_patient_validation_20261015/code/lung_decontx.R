args<-commandArgs(TRUE);stopifnot(length(args)==1)
d<-args[1];out<-file.path(dirname(dirname(d)),'ambient');dir.create(out,showWarnings=FALSE)
suppressPackageStartupMessages({library(Matrix);library(data.table);library(decontX)})
set.seed(20261015)
c<-as.data.frame(fread(file.path(d,'cells.tsv')));g<-as.data.frame(fread(file.path(d,'genes.tsv')))
x<-as(readMM(gzfile(file.path(d,'counts.mtx.gz'))),'CsparseMatrix');dimnames(x)<-list(g$ensembl,c$tool_id)
fit<-decontX(x,z=as.integer(factor(c$provisional_lineage)),verbose=TRUE)
y<-fit$decontXcounts
stopifnot(identical(dimnames(y),dimnames(x)))
fwrite(data.frame(cell_id=c$cell_id,contamination=fit$contamination),file.path(out,'contamination.tsv'),sep='\t')
tmp<-file.path(out,'corrected_counts.mtx');writeMM(y,tmp)
status<-system2('gzip',c('-f',shQuote(tmp)));stopifnot(status==0)
saveRDS(fit,file.path(out,'decontX_result.rds'))
sink(file.path(out,'sessionInfo.txt'));print(sessionInfo());sink()
writeLines('AMBIENT_COMPLETE',file.path(out,'COMPLETE'))
